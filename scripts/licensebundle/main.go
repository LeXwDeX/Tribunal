// Command licensebundle builds the release third-party notices file.
//
// It combines the Go standard library license, Go modules linked into the
// Linux/amd64 server, and npm production packages from web/package-lock.json.
// The output is a single deterministic file: licenses/THIRD_PARTY_NOTICES.txt.
// Run with -check to verify that the checked-in file is current.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
)

const (
	bundleDirName = "licenses"
	noticesName   = "THIRD_PARTY_NOTICES.txt"
	marker        = "Generated by scripts/licensebundle; do not edit. Run the generator instead.\n"
)

type moduleInfo struct {
	Path    string
	Version string
	Dir     string
	Main    bool
}

type packageInfo struct {
	ImportPath string
	Module     *moduleInfo
}

type lockFile struct {
	LockfileVersion int                    `json:"lockfileVersion"`
	Packages        map[string]lockPackage `json:"packages"`
}

type lockPackage struct {
	Version     string `json:"version"`
	Resolved    string `json:"resolved"`
	Integrity   string `json:"integrity"`
	Dev         bool   `json:"dev"`
	DevOptional bool   `json:"devOptional"`
	Link        bool   `json:"link"`
}

type nodePackage struct {
	name        string
	installPath string
	version     string
}

type licenseText struct {
	name string
	text []byte
}

func main() {
	os.Exit(run(os.Args[1:], os.Stdout, os.Stderr, nil))
}

func run(args []string, stdout, stderr io.Writer, list func(string) ([]byte, error)) int {
	fs := flag.NewFlagSet("licensebundle", flag.ContinueOnError)
	fs.SetOutput(stderr)
	root := fs.String("root", ".", "repository root containing go.mod")
	check := fs.Bool("check", false, "verify that licenses/THIRD_PARTY_NOTICES.txt is current")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if fs.NArg() != 0 {
		fmt.Fprintln(stderr, "licensebundle: unexpected arguments")
		return 2
	}
	if list == nil {
		list = goListDeps
	}

	content, err := build(*root, list)
	if err != nil {
		fmt.Fprintf(stderr, "licensebundle: %v\n", err)
		return 1
	}
	target := noticesPath(*root)
	if *check {
		if err := checkBundle(*root, content); err != nil {
			fmt.Fprintf(stderr, "licensebundle: %v\n", err)
			return 1
		}
		fmt.Fprintf(stdout, "licensebundle: %s is up to date\n", target)
		return 0
	}
	if err := writeBundle(*root, content); err != nil {
		fmt.Fprintf(stderr, "licensebundle: %v\n", err)
		return 1
	}
	fmt.Fprintf(stdout, "licensebundle: wrote %s\n", target)
	return 0
}

func goListDeps(root string) ([]byte, error) {
	cmd := exec.Command("go", "list", "-deps", "-json", "./cmd/server")
	cmd.Dir = root
	// The release artifact is the Linux server built by the Dockerfile. Keep
	// the inventory independent of the host that generates it.
	cmd.Env = append(os.Environ(), "GOOS=linux", "GOARCH=amd64", "CGO_ENABLED=0")
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list -deps ./cmd/server (linux/amd64): %w: %s", err, strings.TrimSpace(stderr.String()))
	}
	return out, nil
}

func build(root string, list func(string) ([]byte, error)) ([]byte, error) {
	if err := validateRoot(root); err != nil {
		return nil, err
	}
	data, err := list(root)
	if err != nil {
		return nil, err
	}
	mods, err := linkedModules(data)
	if err != nil {
		return nil, err
	}
	npm, err := runtimePackages(filepath.Join(root, "web", "package-lock.json"))
	if err != nil {
		return nil, err
	}
	goLicense, err := goStandardLibrary()
	if err != nil {
		return nil, err
	}

	var b strings.Builder
	b.WriteString(marker)
	b.WriteString("\nScope: Go standard library, Go modules linked into the Linux/amd64 server, and npm production packages.\n")
	writeSection(&b, "Go standard library", "LICENSE", goLicense)

	for _, mod := range mods {
		title := "Go module: " + mod.Path + " " + mod.Version
		texts, err := packageTexts(title, mod.Dir)
		if err != nil {
			return nil, err
		}
		for _, text := range texts {
			writeSection(&b, title, text.name, text.text)
		}
	}

	for _, pkg := range npm {
		dir, err := npmDir(root, pkg)
		if err != nil {
			return nil, err
		}
		installed, err := installedVersion(dir)
		if err != nil {
			return nil, fmt.Errorf("npm package %s: %w", pkg.name, err)
		}
		if installed != pkg.version {
			return nil, fmt.Errorf("npm package %s: installed version %q does not match lock %q", pkg.name, installed, pkg.version)
		}
		title := "npm package: " + pkg.name + " " + pkg.version
		texts, err := packageTexts(title, dir)
		if err != nil {
			return nil, err
		}
		for _, text := range texts {
			writeSection(&b, title, text.name, text.text)
		}
	}
	return []byte(b.String()), nil
}

func packageTexts(label, dir string) ([]licenseText, error) {
	names, err := licenseFiles(dir)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", label, err)
	}
	if !hasActualLicense(names) {
		return nil, fmt.Errorf("%s: no LICENSE or COPYING file in %s (NOTICE alone is insufficient)", label, dir)
	}
	texts := make([]licenseText, 0, len(names))
	for _, name := range names {
		text, err := readManagedFile(dir, name)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", label, err)
		}
		texts = append(texts, licenseText{name: name, text: text})
	}
	return texts, nil
}

func linkedModules(data []byte) ([]moduleInfo, error) {
	dec := json.NewDecoder(bytes.NewReader(data))
	mods := make(map[string]moduleInfo)
	for {
		var pkg packageInfo
		if err := dec.Decode(&pkg); errors.Is(err, io.EOF) {
			break
		} else if err != nil {
			return nil, fmt.Errorf("parse go list output: %w", err)
		}
		if pkg.Module == nil || pkg.Module.Main || pkg.Module.Path == "" {
			continue
		}
		mod := *pkg.Module
		if mod.Dir == "" {
			return nil, fmt.Errorf("module %s: go list returned no directory", mod.Path)
		}
		if previous, ok := mods[mod.Path]; ok {
			if previous.Version != mod.Version || previous.Dir != mod.Dir {
				return nil, fmt.Errorf("module %s: conflicting versions %s and %s", mod.Path, previous.Version, mod.Version)
			}
			continue
		}
		mods[mod.Path] = mod
	}
	if len(mods) == 0 {
		return nil, errors.New("no third-party Go modules linked into ./cmd/server")
	}
	list := make([]moduleInfo, 0, len(mods))
	for _, mod := range mods {
		list = append(list, mod)
	}
	sort.Slice(list, func(i, j int) bool { return list[i].Path < list[j].Path })
	return list, nil
}

func runtimePackages(lockPath string) ([]nodePackage, error) {
	data, err := os.ReadFile(lockPath)
	if err != nil {
		return nil, fmt.Errorf("read npm lock: %w", err)
	}
	var lock lockFile
	if err := json.Unmarshal(data, &lock); err != nil {
		return nil, fmt.Errorf("parse npm lock: %w", err)
	}
	if lock.Packages == nil {
		return nil, fmt.Errorf("npm lock %s has no packages", lockPath)
	}
	var pkgs []nodePackage
	for key, pkg := range lock.Packages {
		if key == "" || pkg.Link || pkg.Dev || pkg.DevOptional {
			continue
		}
		if !strings.HasPrefix(key, "node_modules/") {
			return nil, fmt.Errorf("npm lock entry %q is not under node_modules", key)
		}
		installPath := strings.TrimPrefix(key, "node_modules/")
		if err := safeInstallPath(installPath); err != nil {
			return nil, err
		}
		if pkg.Version == "" {
			return nil, fmt.Errorf("npm runtime package %s: missing version", installPath)
		}
		if pkg.Resolved == "" {
			return nil, fmt.Errorf("npm runtime package %s: missing resolved URL", installPath)
		}
		if pkg.Integrity == "" {
			return nil, fmt.Errorf("npm runtime package %s: missing integrity hash", installPath)
		}
		pkgs = append(pkgs, nodePackage{
			name:        installPath,
			installPath: installPath,
			version:     pkg.Version,
		})
	}
	if len(pkgs) == 0 {
		return nil, errors.New("npm lock contains no production packages")
	}
	sort.Slice(pkgs, func(i, j int) bool { return pkgs[i].installPath < pkgs[j].installPath })
	return pkgs, nil
}

func safeInstallPath(installPath string) error {
	if installPath == "" || strings.HasPrefix(installPath, "/") || strings.Contains(installPath, `\`) {
		return fmt.Errorf("unsafe npm install path %q", installPath)
	}
	if path.Clean(installPath) != installPath {
		return fmt.Errorf("unsafe npm install path %q", installPath)
	}
	for _, part := range strings.Split(installPath, "/") {
		if part == "" || part == "." || part == ".." {
			return fmt.Errorf("unsafe npm install path %q", installPath)
		}
	}
	return nil
}

func npmDir(root string, pkg nodePackage) (string, error) {
	base := filepath.Join(root, "web", "node_modules")
	info, err := os.Lstat(base)
	if err != nil {
		return "", fmt.Errorf("npm package %s: %w", pkg.name, err)
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return "", fmt.Errorf("npm package %s: %s is a symlink", pkg.name, base)
	}
	if !info.IsDir() {
		return "", fmt.Errorf("npm package %s: %s is not a directory", pkg.name, base)
	}
	dir := filepath.Join(base, filepath.FromSlash(pkg.installPath))
	if !within(base, dir) {
		return "", fmt.Errorf("npm package %s: install path escapes node_modules", pkg.name)
	}
	info, err = os.Lstat(dir)
	if err != nil {
		return "", fmt.Errorf("npm package %s: %w", pkg.name, err)
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return "", fmt.Errorf("npm package %s: %s is a symlink", pkg.name, dir)
	}
	if !info.IsDir() {
		return "", fmt.Errorf("npm package %s: %s is not a directory", pkg.name, dir)
	}
	return dir, nil
}

func installedVersion(dir string) (string, error) {
	data, err := readManagedFile(dir, "package.json")
	if err != nil {
		return "", err
	}
	var pkg struct {
		Version string `json:"version"`
	}
	if err := json.Unmarshal(data, &pkg); err != nil {
		return "", fmt.Errorf("parse package.json: %w", err)
	}
	if pkg.Version == "" {
		return "", errors.New("package.json has no version")
	}
	return pkg.Version, nil
}

func licenseFiles(dir string) ([]string, error) {
	info, err := os.Lstat(dir)
	if err != nil {
		return nil, err
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return nil, fmt.Errorf("%s is a symlink", dir)
	}
	if !info.IsDir() {
		return nil, fmt.Errorf("%s is not a directory", dir)
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var files []string
	for _, entry := range entries {
		if !isLicenseFile(entry.Name()) {
			continue
		}
		info, err := entry.Info()
		if err != nil {
			return nil, err
		}
		if info.Mode()&os.ModeSymlink != 0 {
			return nil, fmt.Errorf("%s is a symlink", filepath.Join(dir, entry.Name()))
		}
		if !info.Mode().IsRegular() {
			return nil, fmt.Errorf("%s is not a regular file", filepath.Join(dir, entry.Name()))
		}
		files = append(files, entry.Name())
	}
	sort.Strings(files)
	return files, nil
}

func hasActualLicense(names []string) bool {
	for _, name := range names {
		if isActualLicenseName(name) {
			return true
		}
	}
	return false
}

// isLicenseFile accepts license and notice text files, including bundled
// component notices such as LICENSE-3RD-PARTY.md and LICENSE-SQLITE. It
// rejects source files whose names merely start with "license", for example
// license.go.
func isLicenseFile(name string) bool {
	return isActualLicenseName(name) || isNoticeName(name)
}

func isActualLicenseName(name string) bool {
	lower := strings.ToLower(name)
	switch lower {
	case "license", "copying", "copying.lesser":
		return true
	}
	for _, prefix := range []string{"license-", "copying-"} {
		if strings.HasPrefix(lower, prefix) {
			return true
		}
	}
	for _, prefix := range []string{"license.", "copying."} {
		if !strings.HasPrefix(lower, prefix) {
			continue
		}
		switch filepath.Ext(lower) {
		case ".md", ".txt", ".rst", ".html":
			return true
		}
	}
	return false
}

func isNoticeName(name string) bool {
	lower := strings.ToLower(name)
	if lower == "notice" || strings.HasPrefix(lower, "notice-") {
		return true
	}
	if strings.HasPrefix(lower, "notice.") {
		switch filepath.Ext(lower) {
		case ".md", ".txt", ".rst", ".html":
			return true
		}
	}
	return false
}

func goStandardLibrary() ([]byte, error) {
	goroot := runtime.GOROOT()
	if goroot == "" {
		return nil, errors.New("Go standard library: GOROOT is empty")
	}
	candidates := []string{filepath.Join(goroot, "LICENSE")}
	// Some distro layouts keep the Go LICENSE one level above GOROOT.
	if parent := filepath.Dir(goroot); parent != goroot {
		candidates = append(candidates, filepath.Join(parent, "LICENSE"))
	}
	for _, candidate := range candidates {
		info, err := os.Lstat(candidate)
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return nil, fmt.Errorf("Go standard library: %w", err)
		}
		if info.Mode()&os.ModeSymlink != 0 {
			return nil, fmt.Errorf("Go standard library: %s is a symlink", candidate)
		}
		if !info.Mode().IsRegular() {
			continue
		}
		data, err := os.ReadFile(candidate)
		if err != nil {
			return nil, fmt.Errorf("Go standard library: %w", err)
		}
		if len(data) == 0 {
			continue
		}
		return data, nil
	}
	return nil, fmt.Errorf("Go standard library: no readable LICENSE at GOROOT %s", goroot)
}

func readManagedFile(dir, name string) ([]byte, error) {
	if name == "" || name == "." || name == ".." || filepath.Base(name) != name {
		return nil, fmt.Errorf("unsafe file name %q", name)
	}
	target := filepath.Join(dir, name)
	if !within(dir, target) {
		return nil, fmt.Errorf("%s escapes %s", target, dir)
	}
	info, err := os.Lstat(target)
	if err != nil {
		return nil, err
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return nil, fmt.Errorf("%s is a symlink", target)
	}
	if !info.Mode().IsRegular() {
		return nil, fmt.Errorf("%s is not a regular file", target)
	}
	data, err := os.ReadFile(target)
	if err != nil {
		return nil, err
	}
	if len(data) == 0 {
		return nil, fmt.Errorf("%s is empty", target)
	}
	return data, nil
}

func within(base, target string) bool {
	base, err := filepath.Abs(base)
	if err != nil {
		return false
	}
	target, err = filepath.Abs(target)
	if err != nil {
		return false
	}
	rel, err := filepath.Rel(base, target)
	if err != nil || filepath.IsAbs(rel) {
		return false
	}
	return rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}

func writeSection(b *strings.Builder, title, file string, text []byte) {
	b.WriteString("\n")
	b.WriteString(strings.Repeat("-", 80))
	b.WriteString("\n")
	b.WriteString(title)
	b.WriteString("\nFile: ")
	b.WriteString(file)
	b.WriteString("\n")
	b.WriteString(strings.Repeat("-", 80))
	b.WriteString("\n")
	b.Write(text)
	if len(text) == 0 || text[len(text)-1] != '\n' {
		b.WriteByte('\n')
	}
}

func writeBundle(root string, content []byte) error {
	if err := validateRoot(root); err != nil {
		return err
	}
	if !bytes.HasPrefix(content, []byte(marker)) {
		return errors.New("bundle content does not start with the generated marker")
	}
	dir := bundleDir(root)
	info, err := os.Lstat(dir)
	switch {
	case errors.Is(err, os.ErrNotExist):
		if err := os.Mkdir(dir, 0o755); err != nil {
			return fmt.Errorf("create bundle directory: %w", err)
		}
		if err := os.Chmod(dir, 0o755); err != nil {
			return fmt.Errorf("set bundle directory permissions: %w", err)
		}
	case err != nil:
		return err
	default:
		if info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("bundle directory %s is a symlink", dir)
		}
		if !info.IsDir() {
			return fmt.Errorf("bundle path %s is not a directory", dir)
		}
		if info.Mode().Perm()&0o055 != 0o055 {
			return fmt.Errorf("bundle directory %s is not readable by non-owner users", dir)
		}
		if err := validateBundleDir(dir); err != nil {
			return err
		}
	}

	target := filepath.Join(dir, noticesName)
	if info, err := os.Lstat(target); err == nil {
		if info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("bundle file %s is a symlink", target)
		}
		if !info.Mode().IsRegular() {
			return fmt.Errorf("bundle file %s is not a regular file", target)
		}
		previous, err := os.ReadFile(target)
		if err != nil {
			return fmt.Errorf("read existing bundle: %w", err)
		}
		if !bytes.HasPrefix(previous, []byte(marker)) {
			return fmt.Errorf("bundle file %s was not generated by licensebundle; refusing to overwrite", target)
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}

	tmp, err := os.CreateTemp(dir, ".notices-*.tmp")
	if err != nil {
		return fmt.Errorf("create temporary bundle file: %w", err)
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	if _, err := tmp.Write(content); err != nil {
		tmp.Close()
		return fmt.Errorf("write temporary bundle file: %w", err)
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return fmt.Errorf("sync temporary bundle file: %w", err)
	}
	if err := tmp.Chmod(0o644); err != nil {
		tmp.Close()
		return fmt.Errorf("set bundle file permissions: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("close temporary bundle file: %w", err)
	}
	if err := os.Rename(tmpName, target); err != nil {
		return fmt.Errorf("replace bundle file: %w", err)
	}
	return nil
}

func checkBundle(root string, content []byte) error {
	if err := validateRoot(root); err != nil {
		return err
	}
	if !bytes.HasPrefix(content, []byte(marker)) {
		return errors.New("bundle content does not start with the generated marker")
	}
	dir := bundleDir(root)
	info, err := os.Lstat(dir)
	if errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("bundle is missing %s", filepath.Join(dir, noticesName))
	}
	if err != nil {
		return err
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("bundle directory %s is a symlink", dir)
	}
	if !info.IsDir() {
		return fmt.Errorf("bundle path %s is not a directory", dir)
	}
	if err := validateBundleDir(dir); err != nil {
		return err
	}
	target := filepath.Join(dir, noticesName)
	info, err = os.Lstat(target)
	if errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("bundle is missing %s", target)
	}
	if err != nil {
		return err
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("bundle file %s is a symlink", target)
	}
	if !info.Mode().IsRegular() {
		return fmt.Errorf("bundle file %s is not a regular file", target)
	}
	actual, err := os.ReadFile(target)
	if err != nil {
		return err
	}
	if !bytes.HasPrefix(actual, []byte(marker)) {
		return fmt.Errorf("bundle file %s was not generated by licensebundle", target)
	}
	if !bytes.Equal(actual, content) {
		return fmt.Errorf("bundle file %s differs from generated content", target)
	}
	return nil
}

func validateBundleDir(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if entry.Name() != noticesName {
			return fmt.Errorf("bundle directory %s contains unknown entry %q; refusing to overwrite", dir, entry.Name())
		}
		info, err := entry.Info()
		if err != nil {
			return err
		}
		if info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("bundle file %s is a symlink", filepath.Join(dir, entry.Name()))
		}
		if !info.Mode().IsRegular() {
			return fmt.Errorf("bundle file %s is not a regular file", filepath.Join(dir, entry.Name()))
		}
	}
	return nil
}

func validateRoot(root string) error {
	abs, err := filepath.Abs(root)
	if err != nil {
		return fmt.Errorf("root %q: %w", root, err)
	}
	if filepath.Dir(abs) == abs {
		return fmt.Errorf("root %q is a filesystem root", root)
	}
	info, err := os.Lstat(abs)
	if err != nil {
		return fmt.Errorf("root %q: %w", root, err)
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("root %q is a symlink", root)
	}
	if !info.IsDir() {
		return fmt.Errorf("root %q is not a directory", root)
	}
	mod, err := os.Lstat(filepath.Join(abs, "go.mod"))
	if err != nil {
		return fmt.Errorf("root %q has no go.mod: %w", root, err)
	}
	if !mod.Mode().IsRegular() {
		return fmt.Errorf("root %q: go.mod is not a regular file", root)
	}
	return nil
}

func bundleDir(root string) string {
	return filepath.Join(root, bundleDirName)
}

func noticesPath(root string) string {
	return filepath.Join(bundleDir(root), noticesName)
}
